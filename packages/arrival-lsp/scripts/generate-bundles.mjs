// generate-bundles — bake the browser entry's virtual files into TS modules.
//
// The Node entry reads the prelude off disk and the TS default libs off the
// installed `typescript` package; a browser bundle can do neither. This script
// generates, at build time:
//   • `src/prelude-bundle.generated.ts` — the PRE prelude + builtin leaves,
//     byte-identical to what `getPreludeFiles()` reads (a vitest guard asserts it);
//   • `src/ts-libs.generated.ts` — the `lib.es2022.d.ts` reference chain resolved
//     off THIS workspace's pinned `typescript`, so the browser service is
//     self-contained (no CDN fetch — the inhuman studio runs offline) and the lib
//     version can never drift from the `typescript` the service runs on.
//
// Run via `pnpm generate:bundles` (build runs it before tsc). Generated files are
// checked in so workspace consumers (vitest/tsx off `src/`) need no build step.

import { createRequire } from "node:module";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(here, "..", "src");
const preludeDir = path.join(srcDir, "prelude");
const builtinsDir = path.join(preludeDir, "builtins");

const HEADER = (what) =>
  `// GENERATED by scripts/generate-bundles.mjs — do not edit.\n// ${what}\n// Regenerate: pnpm generate:bundles\n\n`;

const entryLines = (entries) =>
  entries.map(([k, v]) => `  [${JSON.stringify(k)}, ${JSON.stringify(v)}],`).join("\n");

// ── prelude bundle (mirrors getPreludeFiles in src/prelude.ts) ──────────────
const preludeEntries = [["__pre.d.ts", readFileSync(path.join(preludeDir, "types.d.ts"), "utf8")]];
for (const f of readdirSync(builtinsDir).sort()) {
  if (!f.endsWith(".d.ts") || f.startsWith("_")) continue;
  preludeEntries.push([`__leaf_${f}`, readFileSync(path.join(builtinsDir, f), "utf8")]);
}
writeFileSync(
  path.join(srcDir, "prelude-bundle.generated.ts"),
  HEADER("The PRE prelude + builtin leaves, as `getPreludeFiles()` would read them from disk.") +
    `export const PRELUDE_BUNDLE: readonly (readonly [string, string])[] = [\n${entryLines(preludeEntries)}\n];\n`,
);

// ── TS default-lib bundle: lib.es2022.d.ts + its /// <reference lib/> closure,
//    with every GLOBAL VALUE declaration stripped ("the env is an empty barrel").
//    The checker structurally needs the lib TYPES (interface Array<T>, Promise…)
//    for literals and the prelude's signatures to work — but the ambient VALUES
//    (declare var console/Math…, declare function parseInt…) are the JS
//    environment, which does not exist in scheme. Stripping them makes
//    `(parseInt "3")` a "Cannot find name" bite at the compilation level (not a
//    post-hoc filter) and keeps JS globals out of completions at the source.
const require = createRequire(import.meta.url);
const ts = require("typescript");
const tsLibDir = path.dirname(require.resolve("typescript"));
const ROOT_LIB = "lib.es2022.d.ts";

/** Value declarations the lib TYPES themselves structurally need: computed
 *  properties like `[Symbol.iterator]()` resolve through the VALUE `Symbol` —
 *  dropping it left 93 internal lib errors (audited 2026-06-10: every one a
 *  Symbol cascade; keeping it alone → 0). The completion baseline subtracts
 *  these names anyway, so nothing leaks to the editor surface. */
const KEEP_VALUES = new Set(["Symbol"]);

/** Drop top-level ambient value declarations (vars + functions); keep types
 *  and the KEEP_VALUES the type side needs. Text-splicing on AST ranges —
 *  comments/references outside them survive. */
function stripGlobalValues(name, text) {
  const sf = ts.createSourceFile(name, text, ts.ScriptTarget.Latest, false);
  let out = "";
  let pos = 0;
  for (const s of sf.statements) {
    if (!ts.isVariableStatement(s) && !ts.isFunctionDeclaration(s)) continue;
    if (
      ts.isVariableStatement(s) &&
      s.declarationList.declarations.some((d) => KEEP_VALUES.has(d.name.getText(sf)))
    )
      continue;
    out += text.slice(pos, s.getFullStart());
    pos = s.getEnd();
  }
  return out + text.slice(pos);
}

const libFiles = new Map();
const queue = [ROOT_LIB];
while (queue.length > 0) {
  const name = queue.shift();
  if (libFiles.has(name)) continue;
  const text = readFileSync(path.join(tsLibDir, name), "utf8");
  libFiles.set(name, stripGlobalValues(name, text));
  for (const m of text.matchAll(/\/\/\/\s*<reference\s+lib="([^"]+)"\s*\/>/g)) {
    queue.push(`lib.${m[1]}.d.ts`);
  }
}
writeFileSync(
  path.join(srcDir, "ts-libs.generated.ts"),
  HEADER(
    `The ${ROOT_LIB} reference-chain closure of the workspace's pinned typescript (${require("typescript").version}), global VALUES stripped (types only — scheme has no JS environment).`,
  ) +
    `export const TS_DEFAULT_LIB = ${JSON.stringify(ROOT_LIB)};\n\n` +
    `export const TS_LIB_FILES: readonly (readonly [string, string])[] = [\n${entryLines([...libFiles])}\n];\n`,
);

console.log(
  `generated prelude bundle (${preludeEntries.length} files) + ts libs (${libFiles.size} files, root ${ROOT_LIB})`,
);
