// generate-bundles — prepare the browser entry's virtual files.
//
// The Node entry reads the prelude off disk and the TS default libs off the
// installed `typescript` package (via fs + strip at runtime).
// The browser entry does the same via Vite `import.meta.glob(..., '?raw')` + strip
// (no inlining of huge strings).
//
// This script generates at build time:
//   • `src/ts-libs.generated.ts` — only the small *names* manifest for the
//     lib.es2022 reference chain (so Node and browser load exactly the same set).
//
// Prelude is loaded directly (disk / glob). No generated inlined bundles anymore.
//
// Run via `pnpm generate:bundles`. Generated files checked in for src/ consumers.

import { createRequire } from "node:module";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(here, "..", "src");

const HEADER = (what) =>
  `// GENERATED by scripts/generate-bundles.mjs — do not edit.\n// ${what}\n// Regenerate: pnpm generate:bundles\n\n`;

// ── TS lib manifest (names only).
//
// The concrete *contents* are loaded "directly from ts":
//   • Node / language-service path: fs + strip at load time (see language-service.ts)
//   • Browser / Vite path: import.meta.glob + strip (see browser.ts)
//
// This generated file only bakes the closure list (so both paths load exactly
// the same files, and we stay in sync with the pinned typescript dep).
// No huge strings or per-file re-export barrels are generated.
const require = createRequire(import.meta.url);
const tsLibDir = path.dirname(require.resolve("typescript"));
const ROOT_LIB = "lib.es2022.d.ts";

const libNamesInOrder = [];
const seen = new Set();
const queue = [ROOT_LIB];
while (queue.length > 0) {
  const name = queue.shift();
  if (seen.has(name)) continue;
  seen.add(name);
  libNamesInOrder.push(name);
  const text = readFileSync(path.join(tsLibDir, name), "utf8");
  for (const m of text.matchAll(/\/\/\/\s*<reference\s+lib="([^"]+)"\s*\/>/g)) {
    queue.push(`lib.${m[1]}.d.ts`);
  }
}

writeFileSync(
  path.join(srcDir, "ts-libs.generated.ts"),
  HEADER(
    `The ${ROOT_LIB} reference-chain closure of the workspace's pinned typescript (${require("typescript").version}). Contents are loaded directly from the typescript package (Node: fs; browser: Vite ?raw) and stripped of JS globals. Regenerate if you change the root lib or the TS version.`,
  ) +
    `export const TS_DEFAULT_LIB = ${JSON.stringify(ROOT_LIB)};\n\n` +
    `export const TS_LIB_FILE_NAMES: readonly string[] = [\n${libNamesInOrder.map((n) => `  ${JSON.stringify(n)},`).join("\n")}\n];\n`,
);

// No longer emit a per-file ?raw barrel for the browser path.
// browser.ts now uses import.meta.glob directly (cleaner, no name mangling,
// no long list of export { default as ... }).
// Only the small names manifest is needed so both Node and browser paths load
// exactly the same reference closure.

console.log(
  `generated ts lib manifest (${libNamesInOrder.length} files, root ${ROOT_LIB})`,
);
